    public static function connexion(string $evenement): array
    {
        return self::CONNEXION[$evenement] ?? [self::humaniser($evenement), 'neutral'];
    }

    public static function audit(string $action): array
    {
        return self::AUDIT[$action] ?? [self::humaniser($action), 'neutral'];
    }

    /** Pour la liste déroulante des filtres : clé => libellé. */
    public static function choix(array $table): array
    {
        $choix = array_map(fn ($v) => $v[0], $table);
        asort($choix, SORT_LOCALE_STRING);

        return $choix;
    }

